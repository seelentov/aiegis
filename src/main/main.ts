import { execFile } from 'node:child_process';
import path from 'node:path';
import { app, BrowserWindow, dialog, ipcMain } from 'electron';
import * as pty from 'node-pty';
import { EVENT_CHANNEL, invokeChannel, type ApiImpl, type ApiMethod } from '../shared/api';
import type { AppEvent } from '../shared/types';
import { coreApi } from './api';
import { Core } from './core';
import { acquireLock } from './lock';
import { getLogger, shutdownLogging } from './log';
import { resolveAppPaths } from './paths';
import { adoptLoginShellPath } from './shell-env';

const log = getLogger('core');

let core: Core;
let win: BrowserWindow | null = null;
let releaseLock = (): void => undefined;

function api(): ApiImpl {
  return {
    ...coreApi(core),
    pickAndAddProject: async () => {
      const r = await dialog.showOpenDialog(win!, { properties: ['openDirectory'], title: 'Choose a git repository' });
      if (r.canceled || !r.filePaths[0]) return null;
      return core.addProject(r.filePaths[0]);
    },
    pickDocumentFile: async () => {
      const r = await dialog.showOpenDialog(win!, {
        properties: ['openFile'],
        title: 'Choose a document',
        filters: [{ name: 'MD, PDF, DOCX', extensions: ['md', 'markdown', 'txt', 'pdf', 'docx'] }],
      });
      return r.canceled || !r.filePaths[0] ? null : r.filePaths[0];
    },
    pickScaInputFile: async () => {
      const r = await dialog.showOpenDialog(win!, { properties: ['openFile'], title: 'Dependency file (lock file, SBOM, scanner report)' });
      return r.canceled || !r.filePaths[0] ? null : r.filePaths[0];
    },
    pickSarifFile: async () => {
      const r = await dialog.showOpenDialog(win!, { properties: ['openFile'], title: 'SARIF report', filters: [{ name: 'SARIF', extensions: ['sarif', 'json'] }] });
      return r.canceled || !r.filePaths[0] ? null : r.filePaths[0];
    },
    newSession: (pid) => core.newSession(pid),
    openRun: (pid, runId) => core.openRun(pid, runId),
    openExternal: (pid, runId) => core.openExternal(pid, runId),
    takeOver: (pid, jobId) => core.takeOver(pid, jobId),
    openFixSession: (pid, id) => core.openFixSession(pid, id),
    openInEditor: (file, line, pid) => {
      const abs = pid ? path.resolve(core.listProjects().find((p) => p.id === pid)?.root ?? '', file) : file;
      execFile('code', line ? ['-g', `${abs}:${line}`] : [abs], (err) => {
        if (err) execFile('open', ['-a', 'Visual Studio Code', abs], () => undefined);
      });
    },
    terminalWrite: (id, data) => core.terminals.write(id, data),
    terminalResize: (id, cols, rows) => core.terminals.resize(id, cols, rows),
    uiLanguage: () => core.uiLanguage(),
  };
}

function registerIpc(): void {
  const impl = api();
  for (const name of Object.keys(impl) as ApiMethod[]) {
    const fn = impl[name] as (...a: unknown[]) => unknown;
    // Name only: arguments carry prompts and config text.
    ipcMain.handle(invokeChannel(name), async (_e, ...args: unknown[]) => {
      log.debug('api %s', name);
      return fn(...args);
    });
  }
}

// Generated by `npm run icons` from build/icon.svg.
const ICON = path.join(
  __dirname, '..', 'build',
  process.platform === 'win32' ? 'icon.ico' : process.platform === 'linux' ? 'icons/512x512.png' : 'icon.png',
);

function createWindow(): void {
  // Unpackaged runs show Electron's icon in the Dock unless set explicitly.
  app.dock?.setIcon(ICON);
  win = new BrowserWindow({
    width: 1500,
    height: 950,
    title: 'aiegis',
    icon: ICON,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  void win.loadFile(path.join(__dirname, 'renderer', 'index.html'));
  win.on('closed', () => (win = null));
}

// Must match build.appId: the NSIS shortcut uses it, so the taskbar groups the window under aiegis, not Electron.
if (process.platform === 'win32') app.setAppUserModelId('io.github.seelentov.aiegis');

app.whenReady().then(async () => {
  // Before anything spawns `claude` or scanners: Finder/Dock launches lack the user's shell PATH.
  await adoptLoginShellPath();
  const paths = resolveAppPaths(path.join(__dirname, '..', 'defaults'));
  try {
    releaseLock = acquireLock(paths.dataDir);
  } catch (e) {
    dialog.showErrorBox('aiegis', (e as Error).message);
    app.exit(1);
    return;
  }
  core = new Core(paths, { logging: true, pty: pty.spawn });
  core.on('event', (ev: AppEvent) => win?.webContents.send(EVENT_CHANNEL, ev));
  await core.start();
  registerIpc();
  createWindow();
});

process.on('unhandledRejection', (e) => log.error('unhandled rejection: %s', e));

let quitting = false;
app.on('before-quit', (e) => {
  if (quitting) return;
  e.preventDefault();
  quitting = true;
  core.shutdown().finally(() => {
    releaseLock();
    void shutdownLogging().finally(() => app.quit());
  });
});

app.on('window-all-closed', () => app.quit());
